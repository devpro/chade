// The mark of the host of the remote, an empty place of the same size without a remote so the names stay aligned.
export function forgeIcon(remote: Remote | undefined): HTMLElement {
  const holder = node('span', '', `forge ${remote?.forge ?? 'none'}`)
  if (!remote) {
    holder.title = 'No remote'
    return holder
  }
  const { label, path } = MARKS[remote.forge]
  holder.title = remote.host ? `${remote.name} on ${remote.forge === 'git' ? remote.host : label}` : `${remote.name}, a folder or a host of the local network`
  holder.setAttribute('role', 'img')
  holder.setAttribute('aria-label', holder.title)
  const icon = svg('svg', { viewBox: '0 0 24 24', 'aria-hidden': 'true' })
  icon.append(svg('path', { d: path }))
  holder.append(icon)
  return holder
}
